export function analyzeTone(content: string): { positive: number; negative: number; score: number } {
  const text = content.replace(/<[^>]*>/g, ' ').toLowerCase()
  const words = text.match(/[а-яёa-z]+/g) ?? []
  let positive = 0, negative = 0
  for (const w of words) {
    if (POSITIVE_WORDS.has(w)) positive++
    else if (NEGATIVE_WORDS.has(w)) negative++
  }
  const total = positive + negative
  const score = total === 0 ? 0 : (positive - negative) / total
  return { positive, negative, score }
}
